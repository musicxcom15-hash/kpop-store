-- =====================================================================
-- KPOP STORE — โครงสร้างฐานข้อมูล (PostgreSQL / Supabase)
--
-- ใช้ได้ 2 ที่โดยไม่ต้องแก้:
--   * Supabase  : เปิด SQL Editor → วางทั้งไฟล์ → Run
--   * Docker    : docker compose รันให้เองตอนสร้าง DB ครั้งแรก (ตามด้วย seed.sql)
--
-- ไฟล์นี้มีแต่โครงสร้าง ไม่มีข้อมูล — ข้อมูลตัวอย่างสำหรับเครื่องพัฒนาอยู่ที่ seed.sql
-- (ห้ามรัน seed.sql บนเว็บจริง: มีบัญชีแอดมินรหัส admin123 ที่ทุกคนรู้)
--
-- รันซ้ำได้ แต่ "ลบตารางเดิมทิ้งทั้งหมด" ก่อนสร้างใหม่ — ข้อมูลหายหมด
--
-- ความต่างจาก MySQL รุ่นเดิมที่ต้องรู้:
--   * ENUM → VARCHAR + CHECK (Postgres บังคับ CHECK จริง)
--   * AUTO_INCREMENT → GENERATED BY DEFAULT AS IDENTITY
--   * อีเมลเทียบแบบไม่สนตัวพิมพ์เล็ก/ใหญ่ด้วย lower() (MySQL เดิมได้จาก collation เอง)
--   * เวลาเก็บเป็น TIMESTAMP(0) แบบไม่มีเขตเวลา = "เวลาไทย" ที่ PHP เขียนลงไป เหมือนเดิม
-- =====================================================================

-- เรียงจากตารางลูกไปแม่ (CASCADE กันติด foreign key อยู่แล้ว แต่เรียงไว้ให้อ่านง่าย)
DROP TABLE IF EXISTS sessions CASCADE;
DROP TABLE IF EXISTS cart_items CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS password_resets CASCADE;
DROP TABLE IF EXISTS notifications CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS rounds CASCADE;

-- ---------------------------------------------------------------------
-- rounds — รอบพรีออเดอร์
-- หน้าต่างรับสั่งที่ผูกกับรอบของเว็บเกาหลี หรือรอบที่ร้านเดินทางไปหิ้วเอง
-- สินค้าคนละรอบถึงไทยคนละเวลา
-- ---------------------------------------------------------------------
CREATE TABLE rounds (
    id           VARCHAR(50)  PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    type         VARCHAR(20)  NOT NULL DEFAULT 'korean-site'
                 CHECK (type IN ('korean-site', 'shipping')),
    open_at      DATE         NOT NULL,
    close_at     DATE         NOT NULL,
    -- สถานะที่ร้านกดเอง ถ้าไม่ใช่ open ระบบจะยึดค่านี้เหนือช่วงวันที่
    status       VARCHAR(20)  NOT NULL DEFAULT 'open'
                 CHECK (status IN ('open', 'upcoming', 'closed', 'ordered', 'arrived', 'shipped')),
    est_delivery VARCHAR(255),
    note         TEXT
);

-- ---------------------------------------------------------------------
-- users — บัญชีผู้ใช้
-- รหัสผ่านเก็บเป็น bcrypt จาก password_hash() ตรวจด้วย password_verify() เท่านั้น
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            VARCHAR(50)  PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    phone         VARCHAR(30),
    -- ที่อยู่เต็มสำหรับจ่าหน้าพัสดุ (ระบบประกอบจากช่องด้านล่าง) — บัญชีเก่าอาจมีแค่ช่องนี้
    address       TEXT,
    -- ที่อยู่แบบแยกช่อง ตำบล/อำเภอ/จังหวัด/รหัสไปรษณีย์ตรวจกับ preorderkpopweb/data/thai-address.json
    -- postcode ว่าง = ยังไม่ได้กรอกแบบแยกช่อง → ต้องกรอกก่อนสั่งซื้อ
    address_line  VARCHAR(200) NOT NULL DEFAULT '',
    subdistrict   VARCHAR(100) NOT NULL DEFAULT '',
    district      VARCHAR(100) NOT NULL DEFAULT '',
    province      VARCHAR(100) NOT NULL DEFAULT '',
    postcode      VARCHAR(5)   NOT NULL DEFAULT '',
    role          VARCHAR(20)  NOT NULL DEFAULT 'customer'
                  CHECK (role IN ('admin', 'customer')),
    created_at    DATE         NOT NULL
);
-- อีเมลคือคีย์ที่ผูกออเดอร์กับเจ้าของ ห้ามซ้ำเด็ดขาด (ไม่สนตัวพิมพ์ — A@x.com กับ a@x.com คือคนเดียวกัน)
-- ถ้าซ้ำได้ การสมัครด้วยอีเมลแอดมินจะกลายเป็นการยึดบัญชี
CREATE UNIQUE INDEX uniq_users_email ON users (lower(email));

-- ---------------------------------------------------------------------
-- products — สินค้า
-- ราคาจริงคิดจาก price_krw x เรทกลาง + service_fee
-- คอลัมน์ price เป็นราคาบาทคงที่ของข้อมูลยุคก่อนมีเรท ใช้เป็น fallback เท่านั้น
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id              VARCHAR(50)   PRIMARY KEY,
    artist          VARCHAR(150)  NOT NULL,
    title           VARCHAR(255)  NOT NULL,
    -- album | lightstick | photocard | clothing | popup | merch (ชื่อไทยอยู่ที่ PRODUCT_CATEGORIES ใน js/store.js)
    category        VARCHAR(32)   NOT NULL DEFAULT 'album',
    -- ไซซ์ให้ลูกค้าเลือก คั่นด้วยคอมมา เช่น 'S,M,L,XL' ('' = ไม่มีไซซ์) ราคา/โควตาใช้ร่วมกันทุกไซซ์
    sizes           VARCHAR(255)  NOT NULL DEFAULT '',
    price_krw       INTEGER       NOT NULL DEFAULT 0,
    service_fee     NUMERIC(10,2) NOT NULL DEFAULT 0,
    price           NUMERIC(10,2),
    round_id        VARCHAR(50)   NOT NULL REFERENCES rounds (id) ON DELETE RESTRICT,
    -- NULL = รับไม่จำกัด ห้ามแปลงเป็น 0 เพราะ 0 แปลว่า "เต็มแล้ว"
    quota_per_round INTEGER,
    -- เก็บ path เท่านั้น (images/... หรือ uploads/...)
    image           VARCHAR(255),
    status          VARCHAR(20)   NOT NULL DEFAULT 'PRE-ORDER'
                    CHECK (status IN ('PRE-ORDER', 'OUT OF STOCK')),
    est_delivery    VARCHAR(255),
    -- ชื่อ desc ตรงกับฝั่ง JS แต่เป็น reserved word ของ SQL จึงใช้ description
    description     TEXT,
    -- ลิงก์ร้านต้นทางที่แอดมินไปกดสั่ง (ข้อมูลภายใน bootstrap.php ไม่ส่งให้ลูกค้า)
    source_url      VARCHAR(500)  NOT NULL DEFAULT ''
);
CREATE INDEX idx_products_round ON products (round_id);

-- ---------------------------------------------------------------------
-- orders — หัวคำสั่งซื้อ
--
-- ชื่อ/เบอร์/ที่อยู่เป็น snapshot ตอนสั่ง ตั้งใจไม่ sync กลับจากตาราง users
-- ไม่มีคอลัมน์ status ที่เป็นข้อความไทย — ข้อความ derive จาก status_code
-- ตาม ORDER_STATUS ใน js/store.js ซึ่งเป็นแหล่งความจริงเดียวของทั้งระบบ
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                   VARCHAR(30)   PRIMARY KEY,
    customer_email       VARCHAR(255)  NOT NULL,
    customer_name        VARCHAR(150)  NOT NULL,
    phone                VARCHAR(30),
    address              TEXT,
    order_date           TIMESTAMP(0)  NOT NULL,
    subtotal             NUMERIC(10,2) NOT NULL DEFAULT 0,
    shipping_fee         NUMERIC(10,2) NOT NULL DEFAULT 50,
    total                NUMERIC(10,2) NOT NULL DEFAULT 0,
    status_code          VARCHAR(20)   NOT NULL DEFAULT 'PENDING_SLIP'
                         CHECK (status_code IN (
                             'PENDING_SLIP', 'PAID_WAIT_ROUND', 'ROUND_CLOSED', 'ORDERED_KR',
                             'PREPARING', 'SHIPPING', 'DELIVERED', 'SLIP_REJECTED',
                             'CANCELLED_USER', 'PURCHASE_FAILED', 'REFUND_PENDING', 'REFUNDED'
                         )),
    round_id             VARCHAR(50),
    -- เรทถูกล็อกตอนลูกค้าแนบสลิป หลังจากนั้นเรทเปลี่ยนก็ไม่กระทบออเดอร์ใบนี้
    rate_used            NUMERIC(12,6),
    rate_locked_at       TIMESTAMP(0),
    slip_image           VARCHAR(255),
    tracking_number      VARCHAR(100),
    admin_notes          TEXT,
    purchase_proof_image VARCHAR(255),
    purchase_proof_note  TEXT,
    cancelled_at         TIMESTAMP(0),
    refunded_at          TIMESTAMP(0),
    refund_note          TEXT
);
CREATE INDEX idx_orders_email  ON orders (lower(customer_email));
CREATE INDEX idx_orders_status ON orders (status_code);
CREATE INDEX idx_orders_round  ON orders (round_id);

-- ---------------------------------------------------------------------
-- order_items — รายการสินค้าในออเดอร์
-- title/price/image เป็น snapshot โดยตั้งใจ เพราะสินค้าถูกลบทีหลังได้
-- จึงไม่ผูก foreign key กับ products
-- ---------------------------------------------------------------------
CREATE TABLE order_items (
    id          INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    VARCHAR(30)   NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id  VARCHAR(50)   NOT NULL,
    title       VARCHAR(255)  NOT NULL,
    size        VARCHAR(32)   NOT NULL DEFAULT '',
    qty         INTEGER       NOT NULL DEFAULT 1,
    price       NUMERIC(10,2) NOT NULL DEFAULT 0,
    price_krw   INTEGER,
    service_fee NUMERIC(10,2),
    image       VARCHAR(255)
);
CREATE INDEX idx_items_order   ON order_items (order_id);
CREATE INDEX idx_items_product ON order_items (product_id);

-- ---------------------------------------------------------------------
-- notifications — แจ้งเตือนรายคน
-- user_email ไม่ผูก foreign key เพราะ 'admin@kpopstore.com' ถูกใช้เป็น
-- กล่องรวมของร้าน และแจ้งเตือนต้องอยู่ต่อแม้บัญชีถูกลบ
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email VARCHAR(255) NOT NULL,
    title      VARCHAR(255) NOT NULL,
    message    TEXT         NOT NULL,
    -- เรื่องอะไร + อ้างถึงอะไร: หน้าเว็บใช้ตัดสินว่ากดแจ้งเตือนแล้วพาไปไหน (ดู push_notification ใน helpers.php)
    type       VARCHAR(32),
    ref        VARCHAR(64),
    created_at TIMESTAMP(0) NOT NULL,
    is_read    SMALLINT     NOT NULL DEFAULT 0
);
CREATE INDEX idx_noti_email ON notifications (lower(user_email), is_read);

-- ---------------------------------------------------------------------
-- password_resets — ลิงก์รีเซ็ตรหัสผ่านทางอีเมล (auth.php forgot / reset-with-token)
-- เก็บแค่ hash ของ token ใช้ได้ครั้งเดียว หมดอายุ 30 นาที
-- ไม่ผูก foreign key: users.php ลบ token ของผู้ใช้ที่ถูกลบเอง
-- ---------------------------------------------------------------------
CREATE TABLE password_resets (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(50)  NOT NULL,
    token_hash CHAR(64)     NOT NULL UNIQUE,
    expires_at TIMESTAMP(0) NOT NULL,
    used_at    TIMESTAMP(0),
    created_at TIMESTAMP(0) NOT NULL
);
CREATE INDEX idx_reset_user ON password_resets (user_id, created_at);

-- ---------------------------------------------------------------------
-- cart_items — ตะกร้า (ผูกกับบัญชี)
-- ไม่เก็บราคาโดยตั้งใจ เพราะราคาบาทคิดสดจนกว่าจะแนบสลิป
-- 1 แถว = สินค้า + ไซซ์ (เสื้อตัวเดียวกันคนละไซซ์อยู่คนละแถว) — cart.php ใช้ ON CONFLICT กับ unique นี้
-- ---------------------------------------------------------------------
CREATE TABLE cart_items (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(50)  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id VARCHAR(50)  NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    size       VARCHAR(32)  NOT NULL DEFAULT '',
    qty        INTEGER      NOT NULL DEFAULT 1,
    added_at   TIMESTAMP(0) NOT NULL,
    CONSTRAINT uniq_cart_user_product_size UNIQUE (user_id, product_id, size)
);
CREATE INDEX idx_cart_product ON cart_items (product_id);

-- ---------------------------------------------------------------------
-- sessions — PHP session ของผู้ใช้ (api/session.php)
-- เก็บในฐานข้อมูลเพราะ container บน Vercel ไม่มีดิสก์ถาวร และมีได้หลายตัวพร้อมกัน
-- data คือข้อความที่ PHP serialize เอง (มีแค่ user_id) · หมดอายุตาม session.gc_maxlifetime
-- ---------------------------------------------------------------------
CREATE TABLE sessions (
    id         VARCHAR(128) PRIMARY KEY,
    data       TEXT         NOT NULL,
    updated_at TIMESTAMP(0) NOT NULL
);
CREATE INDEX idx_sessions_updated ON sessions (updated_at);

-- ---------------------------------------------------------------------
-- ความปลอดภัยบน Supabase
--
-- Supabase เปิด REST API อัตโนมัติให้ทุกตารางใน schema public และ anon key ฝังอยู่ในหน้าเว็บได้
-- ถ้าไม่เปิด Row Level Security ใครมี anon key ก็อ่านตาราง users (รวม password_hash) ได้ตรง ๆ
-- เปิด RLS โดยไม่มี policy = REST API อ่าน/เขียนไม่ได้เลย
-- ส่วน PHP ต่อเข้ามาเป็นเจ้าของตาราง (role postgres) จึงไม่ติด RLS ทำงานได้ตามปกติ
-- ---------------------------------------------------------------------
ALTER TABLE rounds          ENABLE ROW LEVEL SECURITY;
ALTER TABLE users           ENABLE ROW LEVEL SECURITY;
ALTER TABLE products        ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders          ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items     ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications   ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE cart_items      ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions        ENABLE ROW LEVEL SECURITY;

-- ปิดสิทธิ์ role ของ REST API ซ้ำอีกชั้น (role พวกนี้มีเฉพาะบน Supabase — Docker ข้ามไป)
DO $$
DECLARE r TEXT;
BEGIN
    FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', r);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', r);
        END IF;
    END LOOP;
END $$;
